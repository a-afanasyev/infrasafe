'use strict';

/**
 * [A-12] Канонизация hex-подписи перед сравнением и дедупом.
 *
 * Находка аудита 08.09.2026: сравнение подписей принимало НЕСКОЛЬКО написаний
 * одной и той же подписи, а ключ дедупа считался по ИСХОДНОЙ строке заголовка.
 *
 * `Buffer.from(value, 'hex')` в Node мягок сознательно: верхний регистр
 * допустим, а первый не-hex символ обрывает разбор — остаток отбрасывается
 * МОЛЧА. Поэтому `abc…`, `ABC…` и `abc…ZZ` декодируются в одни и те же байты,
 * одинаково проходят `timingSafeEqual`, но дают три РАЗНЫХ значения
 * `sha256(signature)`. Имея один валидный пакет, его можно было повторять
 * внутри окна свежести сколько угодно раз, меняя лишь написание подписи.
 *
 * Здесь два решения, и оба намеренные:
 *
 *   - формат проверяется ДО декодирования (строгая hex-строка ожидаемой
 *     длины), поэтому обрезание хвоста больше не может подменить длину;
 *   - регистр приводится к нижнему, а не отвергается. Отправители нам не
 *     подконтрольны (контроллеры, бот УК), `hex` — регистронезависимое
 *     представление, и отказ по регистру был бы поломкой совместимости ради
 *     чистоты. Задача не в том, чтобы запретить написание, а в том, чтобы все
 *     написания сходились к ОДНОМУ ключу дедупа.
 *
 * Длина сверяется с ожидаемым дайджестом, а не с литералом 64: так функция
 * останется верной, если алгоритм подписи когда-нибудь сменится.
 */

const HEX_RE = /^[0-9a-fA-F]+$/;

/**
 * Привести подпись из заголовка к каноническому виду.
 *
 * @param {unknown} signature — значение `v1` из заголовка, как пришло.
 * @param {string} expectedHex — ожидаемый дайджест (hex, нижний регистр).
 * @returns {string|null} канонический hex в нижнем регистре либо `null`,
 *   если подпись не является hex-строкой ожидаемой длины.
 */
function canonicalizeHexSignature(signature, expectedHex) {
    if (typeof signature !== 'string' || typeof expectedHex !== 'string') return null;
    if (signature.length !== expectedHex.length) return null;
    if (!HEX_RE.test(signature)) return null;
    return signature.toLowerCase();
}

module.exports = { canonicalizeHexSignature };
