-- Migration 045 — линия электропередачи обязана принадлежать трансформатору (N-63)
--
-- Решение владельца 07.10.2026: ЛЭП без трансформатора не бывает — линия
-- описывает, откуда приходит питание. До сих пор `lines.transformer_id` был
-- nullable, а в редакторе на карте поле называлось «Опционально».
--
-- Связь и так каскадная (`ON DELETE CASCADE`): удаление трансформатора уносит
-- его линии. Приложение теперь спрашивает подтверждение перед таким удалением
-- (`Transformer.delete(id, { cascadeLines })`), каскад в БД остаётся последним
-- рубежом, а не единственным.
--
-- Тип изменения: CONTRACT, не expand-only. Допустимо, потому что таблица пуста
-- на обеих прод-площадках (проверено 07.10.2026: 0 строк на profk и на .105) и
-- в сидах линий нет. Если строки без трансформатора всё же найдутся — миграция
-- не молчит и не чинит наугад, а падает с понятным текстом: какой трансформатор
-- назначить, решает человек.
--
-- Окно выкатки: раннер применяет миграцию ДО переключения приложения. Старый
-- образ, создающий линию без трансформатора, в это окно получит 500 вместо
-- 201 — путь, которым на проде линий не создавали ни разу (редактор на карте
-- до N-61 не мог создать линию вообще).
--
-- Идемпотентна: SET NOT NULL на уже NOT NULL-колонке — no-op.

BEGIN;

DO $$
DECLARE
    orphan_count INTEGER;
BEGIN
    SELECT count(*) INTO orphan_count FROM lines WHERE transformer_id IS NULL;
    IF orphan_count > 0 THEN
        RAISE EXCEPTION
            '045: % линий без трансформатора — назначьте transformer_id вручную и повторите', orphan_count;
    END IF;
END $$;

ALTER TABLE lines ALTER COLUMN transformer_id SET NOT NULL;

COMMIT;
