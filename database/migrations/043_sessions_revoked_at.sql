-- Migration 043 — рубеж массового отзыва сессий (M-6)
--
-- Что было не так
-- ---------------
-- Реплей refresh-токена ловился (UNIQUE на token_blacklist.token_hash) и
-- отдавал 401 — но ровно на один хэш. При ротации refresh-токенов вор,
-- воспользовавшийся украденным токеном первым, получает свежую пару и живёт
-- со своим семейством до истечения 7 суток. Реплей — это сигнал «токен
-- скомпрометирован», и ответ «заблокировать одну строку» на него не отвечает.
-- Явного «выйти на всех устройствах» тоже не было.
--
-- Почему timestamp, а не token_version
-- ------------------------------------
-- Механизм массовой инвалидации в проекте УЖЕ есть: миграция 016 завела
-- users.password_changed_at, а authService._isIssuedBeforeCutoff отвергает
-- любой токен, чей iat старше этой отметки. Он подключён во всех трёх ветках
-- middleware, в refreshToken и в verifyTempToken. Достаточно второго рубежа и
-- взятия максимума из двух.
--
-- token_version (INTEGER) потребовал бы нового claim'а в payload и ответа на
-- вопрос «что делать с уже выданными токенами, где его нет» — а iat есть в
-- каждом токене по стандарту. Второй столбец, а не переиспользование
-- password_changed_at: смешивать «пароль сменён» и «сессии отозваны» нельзя,
-- первую отметку показывают в аудите и она участвует в отдельной логике
-- 2FA-temp-token'ов.
--
-- Тип изменения: expand-only. Столбец nullable, NULL = «рубежа нет» — то есть
-- ровно текущее поведение для всех существующих строк. Миграция сама по себе
-- НИЧЕГО не меняет в поведении; рубеж появляется только когда его выставит
-- отзыв. Образ отката просто игнорирует незнакомый столбец.

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS sessions_revoked_at TIMESTAMPTZ;

COMMENT ON COLUMN users.sessions_revoked_at IS
    'Миграция 043 (M-6): рубеж массового отзыва сессий. Токены с iat раньше этой отметки отвергаются как протухшие. Выставляется явным "выйти на всех устройствах" и автоматически при обнаружении реплея refresh-токена. NULL = отзыва не было. Работает В ПАРЕ с password_changed_at — cutoff берётся как максимум двух.';
