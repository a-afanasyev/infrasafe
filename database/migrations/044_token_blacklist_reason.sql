-- Migration 044 — причина попадания токена в чёрный список (A-02)
--
-- Что было не так
-- ---------------
-- Реплей refresh-токена должен отзывать всё семейство сессий: повтор — это
-- сигнал компрометации (M-6, миграция 043). Обработчик `_handleRefreshReuse`
-- для этого написан — и по обычному HTTP-пути НЕДОСТИЖИМ. Middleware
-- `authenticateRefresh` (src/middleware/auth.js) проверяет чёрный список ДО
-- сервиса и отдаёт 401 раньше, чем дело дойдёт до атомарного consume. То есть
-- поздний реплей владельца не отзывает сессию того, кто обменял токен первым.
--
-- Почему нельзя просто снять проверку из middleware
-- --------------------------------------------------
-- Тем же чёрным списком пользуется ЛОГАУТ (authController.logout) и 2FA-шаги,
-- которые гасят temp-токен. Убери проверку — и обычный refresh после логаута
-- дойдёт до INSERT, упрётся в UNIQUE и будет прочитан как кража: сработает
-- отзыв всего семейства, то есть пользователя выкинет со ВСЕХ устройств за
-- то, что он вышел на одном. Разные события нельзя лечить одним ответом, пока
-- они неотличимы в данных.
--
-- Что делает миграция
-- -------------------
-- Добавляет `reason` — почему хэш попал в список:
--   'rotation'   — израсходован при ротации refresh (повтор = сигнал кражи);
--   'logout'     — погашен выходом пользователя;
--   'temp-token' — погашен завершением 2FA-шага;
--   'manual'     — прочее (в т.ч. вызовы без указания причины).
-- Отзыв семейства сервис делает ТОЛЬКО для 'rotation'.
--
-- Тип изменения: expand-only. Столбец nullable, без DEFAULT и без backfill'а:
-- NULL = «причина неизвестна» (строки, записанные до этой миграции). Такие
-- строки трактуются как НЕ-rotation, то есть консервативно — 401 без отзыва.
-- Образ отката игнорирует незнакомый столбец, поэтому порядок «схема перед
-- кодом» безопасен в обе стороны.
--
-- Индекса нет намеренно: строка читается по первичному ключу `token_hash`,
-- `reason` только возвращается — отдельный индекс не дал бы ничего, кроме
-- стоимости записи на каждый выданный токен.
--
-- Идемпотентна: ADD COLUMN IF NOT EXISTS + пере-применение CHECK через
-- пересоздание по имени.

BEGIN;

ALTER TABLE token_blacklist
    ADD COLUMN IF NOT EXISTS reason VARCHAR(20);

-- Домен закрепляем на стороне БД: список причин мал и стабилен, а разъехаться
-- он может только молча (урок M-12b на water_lines.status). NULL разрешён явно
-- — это состояние «записано до 044», а не нарушение.
ALTER TABLE token_blacklist
    DROP CONSTRAINT IF EXISTS token_blacklist_reason_check;
ALTER TABLE token_blacklist
    ADD CONSTRAINT token_blacklist_reason_check
    CHECK (reason IS NULL OR reason IN ('rotation', 'logout', 'temp-token', 'manual'));

COMMENT ON COLUMN token_blacklist.reason IS
    'A-02: почему хэш в списке. Отзыв семейства сессий при повторе делается только для rotation; NULL = записано до миграции 044, трактуется как не-rotation.';

COMMIT;
